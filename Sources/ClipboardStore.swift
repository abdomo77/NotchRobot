import AppKit

struct ClipItem: Identifiable, Equatable {
    let id = UUID()
    let text: String
    let date: Date

    var preview: String {
        let one = text.split(separator: "\n").first.map(String.init) ?? text
        let t = one.trimmingCharacters(in: .whitespaces)
        return t.count > 70 ? String(t.prefix(70)) + "…" : t
    }
}

/// آخر حاجات اتعملها copy (نص بس، وفي الرام بس — مش بيتحفظ على الديسك)
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    @Published private(set) var lastCopied: UUID?

    private let pb = NSPasteboard.general
    private var lastChange = NSPasteboard.general.changeCount
    private let limit = 20

    /// مدير الباسوردات بيعلّم الحاجات السرية بالأنواع دي، فبنتجاهلها
    private let ignored: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    func poll() {
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: ignored),
              let s = pb.string(forType: .string),
              !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        let text = String(s.prefix(10_000))
        items.removeAll { $0.text == text }
        items.insert(ClipItem(text: text, date: Date()), at: 0)
        if items.count > limit { items.removeLast(items.count - limit) }
    }

    func copy(_ item: ClipItem) {
        pb.clearContents()
        pb.setString(item.text, forType: .string)
        lastChange = pb.changeCount
        items.removeAll { $0.id == item.id }
        let moved = ClipItem(text: item.text, date: Date())
        items.insert(moved, at: 0)
        lastCopied = moved.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { [weak self] in
            if self?.lastCopied == moved.id { self?.lastCopied = nil }
        }
    }

    func remove(_ item: ClipItem) { items.removeAll { $0.id == item.id } }
    func clear() { items.removeAll() }
}
