import AppKit
import SwiftUI

/// نوع اللي اتنسخ، وكل نوع ليه زرار مناسب
enum ClipKind: Equatable {
    case text, link(URL), email(String), color(Color, hex: String), json, path(URL)

    private static let links = try? NSDataDetector(types: NSTextCheckingResult.CheckingType.link.rawValue)

    static func detect(_ raw: String) -> ClipKind {
        let t = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard t.count < 2000 else { return .text }
        if let c = hexColor(t) { return .color(c, hex: t.uppercased()) }
        if t.hasPrefix("/") || t.hasPrefix("~/"), !t.contains("\n") {
            let u = URL(fileURLWithPath: (t as NSString).expandingTildeInPath)
            if FileManager.default.fileExists(atPath: u.path) { return .path(u) }
        }
        if (t.hasPrefix("{") && t.hasSuffix("}")) || (t.hasPrefix("[") && t.hasSuffix("]")),
           (try? JSONSerialization.jsonObject(with: Data(t.utf8))) != nil { return .json }
        // اللينك أو الإيميل لازم يبقى هو النص كله، مش جوه جملة
        guard !t.contains(where: \.isWhitespace), let links,
              let m = links.firstMatch(in: t, range: NSRange(t.startIndex..., in: t)),
              m.range.length == (t as NSString).length, let u = m.url else { return .text }
        if u.scheme == "mailto" { return .email(String(u.absoluteString.dropFirst("mailto:".count))) }
        // "notch.swift" بيتفهم لينك؛ اللينك الحقيقي فيه scheme أو www
        guard t.contains("://") || t.hasPrefix("www.") else { return .text }
        return .link(u)
    }

    /// #RGB أو #RRGGBB. من غير # مش بنعتبره لون، عشان كود تأكيد زي 482913 ميطلعش لون
    private static func hexColor(_ t: String) -> Color? {
        guard t.hasPrefix("#") else { return nil }
        var h = String(t.dropFirst())
        guard h.count == 3 || h.count == 6, h.allSatisfy(\.isHexDigit) else { return nil }
        if h.count == 3 { h = h.map { "\($0)\($0)" }.joined() }
        guard let v = UInt32(h, radix: 16) else { return nil }
        return Color(red: Double(v >> 16 & 0xFF) / 255, green: Double(v >> 8 & 0xFF) / 255, blue: Double(v & 0xFF) / 255)
    }

    var icon: String {
        switch self {
        case .text: return "text.alignleft"
        case .link: return "link"
        case .email: return "envelope.fill"
        case .color: return "paintpalette.fill"
        case .json: return "curlybraces"
        case .path: return "folder.fill"
        }
    }
}

struct ClipItem: Identifiable, Equatable {
    let id = UUID()
    let text: String
    let date: Date
    let kind: ClipKind

    init(text: String, date: Date) {
        self.text = text
        self.date = date
        kind = ClipKind.detect(text)
    }

    var preview: String {
        let one = text.split(separator: "\n").first.map(String.init) ?? text
        let t = one.trimmingCharacters(in: .whitespaces)
        return t.count > 70 ? String(t.prefix(70)) + "…" : t
    }
}

/// آخر حاجات اتعملها copy (نص بس، وفي الرام بس — مش بيتحفظ على الديسك).
/// اللي بتثبّته بس هو اللي بيتحفظ، عشان دي حاجات إنت اخترتها بنفسك
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    @Published private(set) var pinned: [ClipItem] = []
    @Published private(set) var lastCopied: UUID?

    private let pb = NSPasteboard.general
    private var lastChange = NSPasteboard.general.changeCount
    private let limit = 20
    static let maxPins = 5
    /// عدد الصفوف في التبويب
    static let shown = 6
    private static let pinsKey = "clipPins"

    /// مدير الباسوردات بيعلّم الحاجات السرية بالأنواع دي، فبنتجاهلها
    private let ignored: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    init() {
        pinned = (UserDefaults.standard.stringArray(forKey: Self.pinsKey) ?? []).map { ClipItem(text: $0, date: .distantPast) }
    }

    /// المثبّت الأول، وبعده التاريخ من غير تكرار
    var visible: [ClipItem] {
        let texts = Set(pinned.map(\.text))
        return Array((pinned + items.filter { !texts.contains($0.text) }).prefix(Self.shown))
    }

    func isPinned(_ item: ClipItem) -> Bool { pinned.contains { $0.text == item.text } }

    func poll() {
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: ignored),
              let s = pb.string(forType: .string),
              !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        let text = String(s.prefix(10_000))
        items.removeAll { $0.text == text }
        items.insert(ClipItem(text: text, date: Date()), at: 0)
        if items.count > limit { items.removeLast(items.count - limit) }
    }

    func copy(_ item: ClipItem) {
        put(item.text)
        // المثبّت مكانه ثابت، والباقي بيطلع أول القايمة
        guard !isPinned(item) else { flashCopied(item); return }
        items.removeAll { $0.id == item.id }
        let moved = ClipItem(text: item.text, date: Date())
        items.insert(moved, at: 0)
        flashCopied(moved)
    }

    /// زرار النوع: يفتح اللينك، يكتب إيميل، يرتّب الـ JSON…
    func act(_ item: ClipItem) {
        switch item.kind {
        case .text: copy(item)
        case let .link(u): NSWorkspace.shared.open(u)
        case let .email(e): if let u = URL(string: "mailto:\(e)") { NSWorkspace.shared.open(u) }
        case let .path(u): NSWorkspace.shared.activateFileViewerSelecting([u])
        case let .color(c, _):
            // بيتنسخ بصيغة rgb() عشان الـ CSS
            let n = NSColor(c).usingColorSpace(.sRGB) ?? .black
            put(String(format: "rgb(%d, %d, %d)", Int(n.redComponent * 255), Int(n.greenComponent * 255), Int(n.blueComponent * 255)))
            flashCopied(item)
        case .json:
            guard let o = try? JSONSerialization.jsonObject(with: Data(item.text.utf8)),
                  let d = try? JSONSerialization.data(withJSONObject: o, options: [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]),
                  let pretty = String(data: d, encoding: .utf8) else { return }
            put(pretty)
            flashCopied(item)
        }
    }

    func togglePin(_ item: ClipItem) {
        if isPinned(item) {
            pinned.removeAll { $0.text == item.text }
        } else {
            guard pinned.count < Self.maxPins else { return }
            pinned.append(ClipItem(text: item.text, date: .distantPast))
        }
        UserDefaults.standard.set(pinned.map(\.text), forKey: Self.pinsKey)
    }

    func remove(_ item: ClipItem) {
        if isPinned(item) { togglePin(item) }
        items.removeAll { $0.text == item.text }
    }

    /// المثبّت بيفضل
    func clear() { items.removeAll() }

    /// للصور بتاعة --snapshot بس (من غير ما يلمس الكليب بورد الحقيقي)
    func preview(_ texts: [String], pins: [String]) {
        items = texts.map { ClipItem(text: $0, date: Date().addingTimeInterval(-300)) }
        pinned = pins.map { ClipItem(text: $0, date: .distantPast) }
    }

    private func put(_ s: String) {
        pb.clearContents()
        pb.setString(s, forType: .string)
        lastChange = pb.changeCount
    }

    private func flashCopied(_ item: ClipItem) {
        lastCopied = item.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { [weak self] in
            if self?.lastCopied == item.id { self?.lastCopied = nil }
        }
    }
}
